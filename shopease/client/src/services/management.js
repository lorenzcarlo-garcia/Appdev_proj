import api from './api';
const id=value=>encodeURIComponent(value);
const data=async promise=>(await promise).data;
export const listAdminReports=(params,signal)=>data(api.get('/reports',{params,signal}));
export const getAdminReport=({id:reportId},signal)=>data(api.get(`/reports/${id(reportId)}`,{signal}));
export const listAdminCategories=(_params,signal)=>data(api.get('/categories',{params:{include_inactive:true},signal}));
export const listResidents=(params,signal)=>data(api.get('/residents',{params,signal}));
export const getResident=(residentId)=>data(api.get(`/residents/${id(residentId)}`));
export const createResident=details=>data(api.post('/residents',details));
export const updateResident=(residentId,details)=>data(api.put(`/residents/${id(residentId)}`,details));
export const verifyResident=(residentId,is_verified,expected_token)=>data(api.patch(`/residents/${id(residentId)}/verification`,{is_verified,...(expected_token?{expected_token}:{})}));
export const deleteResident=residentId=>data(api.delete(`/residents/${id(residentId)}`,{data:{confirm:true}}));
export const createCategory=details=>data(api.post('/categories',details));
export const updateCategory=(categoryId,details)=>data(api.put(`/categories/${id(categoryId)}`,details));
export const listBlotters=(params,signal)=>data(api.get('/blotters',{params,signal}));
export const getBlotter=({id:blotterId},signal)=>data(api.get(`/blotters/${id(blotterId)}`,{signal}));
export const createBlotter=details=>data(api.post('/blotters',details));
export const updateBlotter=(blotterId,details)=>data(api.put(`/blotters/${id(blotterId)}`,details));
export const archiveBlotter=blotterId=>data(api.post(`/blotters/${id(blotterId)}/archive`,{confirm:true}));
export const changeReportStatus=(reportId,status,remarks,expected_token)=>data(api.patch(`/reports/${id(reportId)}/status`,{status,remarks:remarks.trim()||null,...(expected_token?{expected_token}:{})}));
export const convertReport=(reportId,details)=>data(api.post(`/reports/${id(reportId)}/blotter`,{...details,confirm:true}));
export const getDashboard=(_params,signal)=>data(api.get('/dashboard',{signal}));
export const getOwnProfile=(_params,signal)=>data(api.get('/auth/profile',{signal}));
export const getOwnStaffProfile=(_params,signal)=>data(api.get('/auth/staff-profile',{signal}));
export const saveOwnStaffProfile=details=>data(api.put('/auth/staff-profile',details));
export const saveOwnProfile=async details=>{
  const result=await data(api.put('/auth/profile',details));
  if(typeof window!=='undefined')window.dispatchEvent(new Event('bantaylog:profile-updated'));
  return result;
};
